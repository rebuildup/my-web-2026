describe('provenance — healthy repository', () => {
	it('passes when manifest, gitlink, checkout, origin and artefact agree', () => {
		const result = run([widgetTool()], GITMODULES, healthyFacts());
		assert.equal(result.ok, true);
		assert.deepEqual(codes(result), []);
		assert.equal(result.rows.length, 1);
		assert.equal(result.rows[0].verdict, 'PASS');
		assert.equal(result.rows[0].checkout_sha, PIN_A);
	});

	it('keeps the recorded pin when the artefact stamp agrees', () => {
		const result = run([widgetTool()], GITMODULES, healthyFacts());
		assert.equal(result.rows[0].artifact_pin, PIN_A);
	});
});

describe('provenance — pinned SHA vs actual source SHA (Issue #473 headline)', () => {
	it('fails when the checked-out commit is not the pinned commit', () => {
		const facts = healthyFacts({
			checkouts: {
				'external/example-widget': {
					initialised: true,
					head: PIN_B,
					origin: CANONICAL,
					dirty: false,
					toplevelMatches: true,
				},
			},
		});
		const result = run([widgetTool()], GITMODULES, facts);
		assert.equal(result.ok, false);
		assert.ok(codes(result).includes('CHECKOUT_SHA_MISMATCH'));
		assert.equal(result.rows[0].verdict, 'FAIL');
		const finding = result.findings.find((item) => item.code === 'CHECKOUT_SHA_MISMATCH');
		assert.match(finding.message, new RegExp(PIN_B));
		assert.match(finding.message, new RegExp(PIN_A));
		assert.match(finding.remedy, /git -C external\/example-widget checkout/);
	});

	it('fails when the gitlink is not the pinned commit', () => {
		const facts = healthyFacts({ gitlinks: { 'external/example-widget': PIN_B } });
		const result = run([widgetTool()], GITMODULES, facts);
		assert.equal(result.ok, false);
		assert.ok(codes(result).includes('GITLINK_SHA_MISMATCH'));
	});

	it('fails when the pin is not a 40-char commit SHA', () => {
		const tool = widgetTool();
		tool.source.pinned_sha = 'main';
		const result = run([tool], GITMODULES, healthyFacts());
		assert.equal(result.ok, false);
		assert.ok(codes(result).includes('PINNED_SHA_INVALID'));
	});
});

describe('provenance — fetch source identity', () => {
	it('fails when .gitmodules fetches a different repository than the manifest declares', () => {
		const gitmodules = parseGitmodules(`
[submodule "external/example-widget"]
	path = external/example-widget
	url = https://github.com/example-org/example-widget-fork.git
`);
		const result = run([widgetTool()], gitmodules, healthyFacts());
		assert.equal(result.ok, false);
		assert.ok(codes(result).includes('URL_MISMATCH'));
	});

	it('fails when .gitmodules uses a non-https or credentialed transport', () => {
		const gitmodules = parseGitmodules(`
[submodule "external/example-widget"]
	path = external/example-widget
	url = https://example-org:ghp_EXAMPLE@github.com/example-org/example-widget.git
`);
		const result = run([widgetTool()], gitmodules, healthyFacts());
		assert.equal(result.ok, false);
		assert.ok(codes(result).includes('URL_UNSAFE'));
	});

	it('fails when local git config redirects the submodule fetch', () => {
		const facts = healthyFacts({
			localSubmoduleConfig: {
				'external/example-widget': {
					url: 'https://github.com/example-org/example-widget-fork.git',
					active: 'true',
				},
			},
		});
		const result = run([widgetTool()], GITMODULES, facts);
		assert.equal(result.ok, false);
		assert.ok(codes(result).includes('LOCAL_URL_OVERRIDE'));
	});

	it('fails when a url.<x>.insteadOf rewrite can redirect the fetch', () => {
		const facts = healthyFacts({
			urlRewrites: [
				{
					scope: '--global',
					key: 'url.https://github.com/example-org/example-widget.git.insteadof',
					value: 'https://',
				},
			],
		});
		const result = run([widgetTool()], GITMODULES, facts);
		assert.equal(result.ok, false);
		assert.ok(codes(result).includes('URL_INSTEADOF_REWRITE'));
	});

	it('fails when a submodule is fetched without a manifest entry', () => {
		const result = run([], GITMODULES, healthyFacts());
		assert.equal(result.ok, false);
		assert.ok(codes(result).includes('SUBMODULE_UNDECLARED'));
	});

	it('fails when a served Tool has no .gitmodules entry to fetch from', () => {
		const result = run([widgetTool()], [], healthyFacts({ gitlinks: {} }));
		assert.equal(result.ok, false);
		assert.ok(codes(result).includes('DECLARED_DELIVERY_UNFETCHABLE'));
	});
});

