/**
 * Issue #473 — the Tool submodule supply-chain provenance gate.
 *
 * Two layers:
 *
 *   1. Pure verification over injected facts. Every provenance rule
 *      (pinned SHA vs actual source SHA, fetch-source mismatch, branch
 *      -tip tracking, artefact drift) is reachable without a network,
 *      a Tool checkout, or a secret.
 *   2. An end-to-end run of the real CLI against synthetic git
 *      repositories built with plumbing only (`git init`,
 *      `git update-index --cacheinfo`, `git commit`). No network, no
 *      real Tool repo, no credential. This is what proves the gate
 *      fails when the pinned SHA and the actual source SHA disagree
 *      using the same git commands CI runs.
 *
 * Every test here is offline and hermetic: git is invoked with
 * `GIT_CONFIG_GLOBAL=/dev/null` so a developer's own `url.*.insteadOf`
 * rewrite or submodule config cannot change the outcome.
 */

