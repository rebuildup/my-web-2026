#!/usr/bin/env node
/**
 * Per-route initial JS / CSS budget gate (Issue #482).
 *
 * What this measures
 * ------------------
 * For every route in `src/routeTree.gen.ts` it computes the set of files a
 * browser must download before that route is interactive — the client entry
 * (`src/client.tsx`) plus the transitive closure of **static** imports of the
 * route's own chunk. Dynamic imports are never walked: a lazy chunk is not
 * charged to first paint.
 *
 * The input is `dist/client/bundle-graph.json`, written by the
 * `my-web-2026:client-bundle-graph` Vite plugin during `pnpm run build`.
 * Reading the build graph (rather than loading pages in a browser) is what
 * makes this measurement free of browser, network and CPU variance — see
 * `quality/bundle-budget.json#measurement` for the recorded reproduction
 * conditions, which this script also prints on every failure so a red CI log
 * carries them.
 *
 * What this does NOT do
 * ---------------------
 * It is a *byte* budget for shipped assets. It is not a Lighthouse score, not
 * a Core Web Vitals measurement, and not a rendering-speed gate — those are
 * Issues #384 / #385 / #386. Keeping the three apart is an acceptance
 * criterion of this Issue, not an accident of scope.
 *
 * Tool iframe bundles
 * -------------------
 * `/tools/<slug>/app/**` is a separate Vite build per Tool with its own
 * `index.html`; its bytes are never part of a host route's first paint. They
 * are aggregated separately (`tool_iframe`) so one heavy Tool cannot mask a
 * heavy route, and vice versa.
 *
 * Usage
 * -----
 *   node scripts/check-bundle-budget.mjs
 *   node scripts/check-bundle-budget.mjs --json
 *   node scripts/check-bundle-budget.mjs --report=.tmp/bundle-budget.json
 *   node scripts/check-bundle-budget.mjs --graph=<path> --budget=<path>
 *
 * Exit codes: 0 = within budget, 1 = violation or acknowledged exception that
 * ran out of budget, 2 = bad input (missing build output, malformed budget).
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_GRAPH = join(REPO_ROOT, 'dist', 'client', 'bundle-graph.json');
const DEFAULT_BUDGET = join(REPO_ROOT, 'quality', 'bundle-budget.json');
const DEFAULT_ROUTE_TREE = join(REPO_ROOT, 'src', 'routeTree.gen.ts');
const DEFAULT_TOOLS_DIR = join(REPO_ROOT, 'dist', 'client', 'tools');

/**
 * A documented exception must explain itself. Short reasons are rejected by
 * the validator: "because" is not a reason, and an unreasoned exception is
 * indistinguishable from disabling the gate.
 */
const MIN_EXCEPTION_REASON_LENGTH = 20;

function parseArg(argv, name) {
	for (const arg of argv) {
		if (arg.startsWith(`${name}=`)) return arg.slice(name.length + 1);
	}
	return null;
}

function formatBytes(bytes) {
	const kb = bytes / 1024;
	return kb >= 1024 ? `${(kb / 1024).toFixed(2)} MiB` : `${kb.toFixed(1)} KiB`;
}

/**
 * Map every routable path to the `src/routes/<file>.tsx` that renders it.
 *
 * `src/routeTree.gen.ts` is generated by TanStack Router and committed, so it
 * is a stable, reviewable source of truth for "which file is this route".
 * `FileRoutesByFullPath` is the interface that maps every route file to the
 * URL that renders it; the `import { Route as X } from './routes/<file>'`
 * lines at the top of the same file map that back to a file.
 *
 * `FileRoutesByFullPath` is used rather than `FileRoutesByTo` because the
 * latter collapses the `/admin` layout route and its `/admin/` index route
 * onto the same key, which would silently drop a route from the budget. Index
 * routes therefore appear with their full path, trailing slash included
 * (`/portfolio/`, `/tools/`, `/admin/`).
 *
 * Deriving the list from the generated tree rather than hand-listing it in the
 * budget file is what makes an unbudgeted NEW route a hard failure instead of
 * a silently unbudgeted page.
 */
export function parseRouteTree(source) {
	// `<file>` for the import alias: `import { Route as IndexRouteImport } from './routes/index'`
	const filesByImportAlias = new Map();
	for (const match of source.matchAll(
		/^import \{ Route as (\w+) \} from '\.\/(routes\/[^']+)';?$/gm,
	)) {
		filesByImportAlias.set(match[1], match[2]);
	}

	// The route const for each import alias: `const IndexRoute = IndexRouteImport.update({`.
	// A layout route re-exported as `AdminRouteWithChildren = AdminRoute._addFileChildren(...)`
	// resolves through the same chain. `FileRoutesByFullPath` is keyed by the
	// const, not by the import alias, so the two names have to be joined before
	// a route path can name a file.
	const importAliasByConst = new Map();
	for (const match of source.matchAll(
		/^const (\w+) = (\w+)\.(?:update|_addFileChildren|addChildren|createFileRoute)\(/gm,
	)) {
		importAliasByConst.set(match[1], match[2]);
	}

	// `AdminRouteWithChildren = AdminRoute._addFileChildren(...)` is a second
	// hop, so the const -> alias link has to be walked until it reaches an
	// actual import alias.
	function fileForConst(constName, seen = new Set()) {
		const direct = filesByImportAlias.get(constName);
		if (direct) return direct;
		if (seen.has(constName)) return undefined;
		seen.add(constName);
		const parent = importAliasByConst.get(constName);
		return parent ? fileForConst(parent, seen) : undefined;
	}

	const block = /export interface FileRoutesByFullPath \{([\s\S]*?)\n\}/.exec(source);
	if (!block) {
		throw new Error('routeTree.gen.ts: FileRoutesByFullPath interface not found');
	}

	const routes = new Map();
	for (const line of block[1].split('\n')) {
		const match = /^\s*'([^']*)': typeof (\w+)\s*$/.exec(line);
		if (!match) continue;
		const file = fileForConst(match[2]);
		if (!file) continue;
		routes.set(match[1], `src/${file}.tsx`);
	}
	if (routes.size === 0) {
		throw new Error('routeTree.gen.ts: FileRoutesByFullPath produced no routes');
	}
	return routes;
}

/** Transitive closure of static imports, starting from `entry`. */
function closureOf(graph, entry) {
	const seen = new Set();
	const stack = [entry];
	while (stack.length > 0) {
		const file = stack.pop();
		if (seen.has(file)) continue;
		const chunk = graph.chunks[file];
		if (!chunk) continue;
		seen.add(file);
		for (const dep of chunk.imports) stack.push(dep);
	}
	return seen;
}

function sumGraph(graph, files) {
	let bytes = 0;
	let gzipBytes = 0;
	const cssFiles = new Set();
	for (const file of files) {
		const chunk = graph.chunks[file];
		if (!chunk) continue;
		bytes += chunk.bytes;
		gzipBytes += chunk.gzip_bytes;
		for (const css of chunk.css) cssFiles.add(css);
	}
	let cssBytes = 0;
	let cssGzipBytes = 0;
	for (const css of cssFiles) {
		const asset = graph.assets[css];
		if (!asset) continue;
		cssBytes += asset.bytes;
		cssGzipBytes += asset.gzip_bytes;
	}
	return { bytes, gzipBytes, cssBytes, cssGzipBytes };
}

/**
 * Compute the per-route measurement table.
 *
 * Every route in the generated tree is mapped to its client chunk. A route
 * whose file produced no client chunk is reported with `chunk: null` and zero
 * bytes; the caller turns that into a violation, because "the route exists but
 * was not measured" is exactly the silent gap this gate exists to close.
 */
export function measureRoutes(graph, routesByPath) {
	const entries = Object.entries(graph.chunks).filter(([, chunk]) => chunk.is_entry);
	if (entries.length !== 1) {
		throw new Error(`bundle-graph: expected exactly 1 client entry chunk, found ${entries.length}`);
	}
	const entryFile = entries[0][0];
	const shell = closureOf(graph, entryFile);
	const shellTotals = sumGraph(graph, shell);

	// One route file can own two chunks: TanStack Start splits the route
	// component from its not-found component under the same module id. Only
	// the `component` split is fetched to render the route, so it wins.
	const byFacade = new Map();
	const facades = new Set();
	for (const [file, chunk] of Object.entries(graph.chunks)) {
		if (!chunk.facade_module_id) continue;
		facades.add(chunk.facade_module_id);
		const existing = byFacade.get(chunk.facade_module_id);
		if (existing === undefined) {
			byFacade.set(chunk.facade_module_id, file);
			continue;
		}
		if ((graph.chunks[existing].facade_query ?? '') === '' && chunk.facade_query) {
			byFacade.set(chunk.facade_module_id, file);
		}
	}

	const routes = [];
	for (const [route, routeFile] of [...routesByPath].sort(([a], [b]) => (a < b ? -1 : 1))) {
		const chunkFile = byFacade.get(routeFile) ?? null;
		if (chunkFile === null) {
			routes.push({
				route,
				route_file: routeFile,
				chunk: null,
				initial_js_bytes: 0,
				initial_js_gzip_bytes: 0,
				initial_css_bytes: 0,
				initial_css_gzip_bytes: 0,
				route_js_bytes: 0,
				route_added_js_bytes: 0,
			});
			continue;
		}
		const files = new Set([...shell, ...closureOf(graph, chunkFile)]);
		const totals = sumGraph(graph, files);
		const routeOnly = closureOf(graph, chunkFile);
		let addedBytes = 0;
		for (const file of routeOnly) {
			if (shell.has(file)) continue;
			addedBytes += graph.chunks[file]?.bytes ?? 0;
		}
		routes.push({
			route,
			route_file: routeFile,
			chunk: chunkFile,
			initial_js_bytes: totals.bytes,
			initial_js_gzip_bytes: totals.gzipBytes,
			initial_css_bytes: totals.cssBytes,
			initial_css_gzip_bytes: totals.cssGzipBytes,
			route_js_bytes: graph.chunks[chunkFile].bytes,
			route_added_js_bytes: addedBytes,
		});
	}

	return { entry: entryFile, shell, shellTotals, routes, facades };
}

/**
 * Compare measurements against the budget file.
 *
 * A violation is a measurement above its cap with no acknowledged exception.
 * An acknowledged exception is a cap that is knowingly above the measurement
 * AND carries a reason; it is reported loudly but does not fail, because a
 * documented, reasoned overage is a decision, not an accident. An exception
 * without a usable reason is a configuration error and always fails — that is
 * the only way the exception mechanism can be abused, so it is closed.
 */
export function evaluateBudgets({ routes, budget }) {
	const violations = [];
	const exceptions = [];
	const warnings = [];

	for (const route of routes) {
		const cap = budget.routes?.[route.route];
		if (!cap) {
			violations.push({
				kind: 'unbudgeted-route',
				route: route.route,
				message: `route ${route.route} has no entry in the bundle budget — add one (a new route is never implicitly free)`,
			});
			continue;
		}
		if (route.chunk === null) {
			violations.push({
				kind: 'unmeasured-route',
				route: route.route,
				message: `route ${route.route} (${route.route_file}) produced no client chunk — the measurement would silently pass at 0 bytes`,
			});
		}
		for (const metric of ['initial_js_bytes', 'initial_css_bytes']) {
			const limit = cap[metric];
			if (typeof limit !== 'number') {
				violations.push({
					kind: 'missing-cap',
					route: route.route,
					message: `route ${route.route} budget is missing "${metric}"`,
				});
				continue;
			}
			const measured = route[metric];
			const overage = measured - limit;
			const exception = cap.exception;
			if (overage > 0 && (!exception || exception.metric !== metric)) {
				violations.push({
					kind: 'budget-exceeded',
					route: route.route,
					metric,
					measured,
					limit,
					overage,
					message: `${route.route} ${metric}=${measured} (${formatBytes(measured)}) exceeds the budget ${limit} (${formatBytes(limit)}) by ${formatBytes(overage)}`,
				});
				continue;
			}
			if (exception && exception.metric === metric) {
				if (overage <= 0) {
					warnings.push({
						kind: 'stale-exception',
						route: route.route,
						message: `${route.route} carries an acknowledged exception for ${metric} but now measures ${measured} <= ${limit} — remove the exception`,
					});
				} else {
					exceptions.push({
						route: route.route,
						metric,
						measured,
						limit,
						overage,
						reason: exception.reason,
					});
				}
			}
		}
	}

	for (const route of Object.keys(budget.routes ?? {})) {
		if (!routes.some((r) => r.route === route)) {
			warnings.push({
				kind: 'stale-budget',
				route,
				message: `budget entry "${route}" has no matching route in the generated route tree`,
			});
		}
	}

	return { violations, exceptions, warnings };
}

function listFilesRecursively(dir) {
	const out = [];
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		const path = join(dir, entry.name);
		if (entry.isDirectory()) out.push(...listFilesRecursively(path));
		else out.push(path);
	}
	return out;
}

/**
 * Aggregate the Tool iframe bundles separately from the host routes.
 *
 * Each Tool is its own Vite build with its own `index.html`, loaded inside a
 * sandboxed iframe. Charging its bytes to `/tools` would both overstate the
 * host route and let a heavy Tool hide behind the host's cap, so the two are
 * measured and capped independently.
 */
export function measureToolBundles(toolsDir) {
	if (!existsSync(toolsDir)) return [];
	const bundles = [];
	for (const entry of readdirSync(toolsDir, { withFileTypes: true })) {
		if (!entry.isDirectory()) continue;
		const slugDir = join(toolsDir, entry.name);
		const files = listFilesRecursively(slugDir).filter((file) => statSync(file).isFile());
		let jsBytes = 0;
		let cssBytes = 0;
		let jsFiles = 0;
		let cssFiles = 0;
		for (const file of files) {
			if (file.endsWith('.js') || file.endsWith('.mjs')) {
				jsBytes += statSync(file).size;
				jsFiles += 1;
			} else if (file.endsWith('.css')) {
				cssBytes += statSync(file).size;
				cssFiles += 1;
			}
		}
		bundles.push({
			slug: entry.name,
			js_bytes: jsBytes,
			css_bytes: cssBytes,
			js_files: jsFiles,
			css_files: cssFiles,
		});
	}
	return bundles.sort((a, b) => (a.slug < b.slug ? -1 : 1));
}

export function evaluateToolBudgets(bundles, budget) {
	const cap = budget.tool_iframe;
	const violations = [];
	if (!cap) return violations;
	for (const bundle of bundles) {
		for (const [metric, limitKey] of [
			['js_bytes', 'max_js_bytes_per_tool'],
			['css_bytes', 'max_css_bytes_per_tool'],
		]) {
			const limit = cap[limitKey];
			if (typeof limit !== 'number') {
				violations.push({
					kind: 'missing-cap',
					route: `tool:${bundle.slug}`,
					message: `tool_iframe budget is missing "${limitKey}"`,
				});
				continue;
			}
			if (bundle[metric] > limit) {
				violations.push({
					kind: 'tool-budget-exceeded',
					route: `tool:${bundle.slug}`,
					metric,
					measured: bundle[metric],
					limit,
					overage: bundle[metric] - limit,
					message: `tool "${bundle.slug}" ${metric}=${bundle[metric]} (${formatBytes(bundle[metric])}) exceeds the separate Tool budget ${limit} (${formatBytes(limit)})`,
				});
			}
		}
	}
	return violations;
}

function validateBudget(budget, routePaths) {
	const errors = [];
	if (budget.schema_version !== 1) {
		errors.push(`schema_version: expected 1, got ${JSON.stringify(budget.schema_version)}`);
	}
	if (!budget.measurement || typeof budget.measurement !== 'object') {
		errors.push(
			'measurement: required — the reproduction conditions must be recorded with the numbers',
		);
	}
	if (!budget.routes || typeof budget.routes !== 'object') {
		errors.push('routes: required');
	}
	for (const [route, cap] of Object.entries(budget.routes ?? {})) {
		if (!routePaths.has(route)) {
			errors.push(`routes["${route}"]: not a route in src/routeTree.gen.ts`);
		}
		const exception = cap.exception;
		if (!exception) continue;
		if (typeof exception.metric !== 'string')
			errors.push(`routes["${route}"].exception.metric: required`);
		if (
			typeof exception.reason !== 'string' ||
			exception.reason.trim().length < MIN_EXCEPTION_REASON_LENGTH
		) {
			errors.push(
				`routes["${route}"].exception.reason: required, at least ${MIN_EXCEPTION_REASON_LENGTH} characters — an unreasoned exception is a disabled gate`,
			);
		}
	}
	if (budget.tool_iframe !== undefined) {
		const reason = budget.tool_iframe.reason;
		if (typeof reason !== 'string' || reason.trim().length < MIN_EXCEPTION_REASON_LENGTH) {
			errors.push(
				`tool_iframe.reason: required, at least ${MIN_EXCEPTION_REASON_LENGTH} characters — a Tool bundle size is not self-evident`,
			);
		}
	}
	return errors;
}

function currentSha() {
	try {
		return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: REPO_ROOT, encoding: 'utf8' }).trim();
	} catch {
		return null;
	}
}

function renderText(report) {
	const lines = [];
	lines.push('[bundle-budget] per-route initial JS/CSS budget (Issue #482)');
	lines.push(`[bundle-budget] source sha : ${report.source_sha ?? 'unknown'}`);
	for (const [key, value] of Object.entries(report.measurement ?? {})) {
		lines.push(`[bundle-budget] condition ${key}: ${value}`);
	}
	lines.push(
		`[bundle-budget] client entry: ${report.entry} (shell js=${formatBytes(report.shell_js_bytes)}, css=${formatBytes(report.shell_css_bytes)})`,
	);
	lines.push('');
	lines.push('route                     initial JS      (+route)  initial CSS   verdict');
	lines.push('------------------------  --------------  ---------  -----------  -------');
	for (const route of report.routes) {
		const verdict = report.violations.some((v) => v.route === route.route)
			? 'OVER'
			: report.exceptions.some((e) => e.route === route.route)
				? 'EXEMPT'
				: 'ok';
		lines.push(
			`${route.route.padEnd(24)}  ${formatBytes(route.initial_js_bytes).padEnd(14)}  ${formatBytes(route.route_added_js_bytes).padEnd(9)}  ${formatBytes(route.initial_css_bytes).padEnd(11)}  ${verdict}`,
		);
	}
	lines.push('');
	if (report.tool_iframe.length === 0) {
		lines.push('[bundle-budget] tool iframe bundles: none present in the build output');
	} else {
		let toolJs = 0;
		let toolCss = 0;
		for (const bundle of report.tool_iframe) {
			toolJs += bundle.js_bytes;
			toolCss += bundle.css_bytes;
			lines.push(
				`[bundle-budget] tool "${bundle.slug}": js=${formatBytes(bundle.js_bytes)} (${bundle.js_files} file(s)), css=${formatBytes(bundle.css_bytes)} (${bundle.css_files} file(s))`,
			);
		}
		lines.push(
			`[bundle-budget] tool iframe aggregate: js=${formatBytes(toolJs)}, css=${formatBytes(toolCss)} (budgeted separately from host routes)`,
		);
	}
	return lines.join('\n');
}

export function buildReport({ graph, routesByPath, toolsDir, budget, sourceSha }) {
	const measured = measureRoutes(graph, routesByPath);
	const routeVerdicts = evaluateBudgets({ routes: measured.routes, budget });
	const toolBundles = measureToolBundles(toolsDir);
	const toolViolations = evaluateToolBudgets(toolBundles, budget);

	// Any client chunk owned by a file under `src/routes/` that the generated
	// route tree does not list is code the browser downloads on some URL this
	// gate does not account for. Ignoring it would let a route grow past its
	// budget by moving code into an "unlisted" file.
	const listed = new Set(routesByPath.values());
	const uncovered = [];
	for (const facade of [...measured.facades].sort()) {
		if (!facade.startsWith('src/routes/') || listed.has(facade)) continue;
		uncovered.push(facade);
	}
	const uncoveredViolations = uncovered
		.filter((facade) => facade !== 'src/routes/__root.tsx')
		.map((facade) => ({
			kind: 'uncovered-route-chunk',
			route: facade,
			message: `client chunk for ${facade} is not reachable from any route in FileRoutesByFullPath — its bytes are not budgeted anywhere`,
		}));
	const uncoveredWarnings = uncovered
		.filter((facade) => facade === 'src/routes/__root.tsx')
		.map((facade) => ({
			kind: 'root-route-chunk',
			route: facade,
			message: `${facade} now has its own client chunk; confirm it is part of every route's initial payload (it is currently folded into the entry)`,
		}));

	return {
		schema_version: 1,
		source_sha: sourceSha,
		measurement: budget.measurement,
		entry: measured.entry,
		shell_js_bytes: measured.shellTotals.bytes,
		shell_css_bytes: measured.shellTotals.cssBytes,
		routes: measured.routes,
		tool_iframe: toolBundles,
		tool_iframe_reason: budget.tool_iframe?.reason ?? null,
		violations: [...routeVerdicts.violations, ...uncoveredViolations, ...toolViolations],
		exceptions: routeVerdicts.exceptions,
		warnings: [...routeVerdicts.warnings, ...uncoveredWarnings],
	};
}

function main(argv) {
	const graphPath = resolve(parseArg(argv, '--graph') ?? DEFAULT_GRAPH);
	const budgetPath = resolve(parseArg(argv, '--budget') ?? DEFAULT_BUDGET);
	const routeTreePath = resolve(parseArg(argv, '--route-tree') ?? DEFAULT_ROUTE_TREE);
	const toolsDir = resolve(parseArg(argv, '--tools') ?? DEFAULT_TOOLS_DIR);
	const reportPath = parseArg(argv, '--report');
	const asJson = argv.includes('--json');

	if (!existsSync(graphPath)) {
		console.error(
			`[bundle-budget] missing client bundle graph: ${graphPath}\nRun \`pnpm run build\` first — the graph is produced by the Vite build, not by this script.`,
		);
		return 2;
	}
	if (!existsSync(routeTreePath)) {
		console.error(`[bundle-budget] missing generated route tree: ${routeTreePath}`);
		return 2;
	}
	if (!existsSync(budgetPath)) {
		console.error(`[bundle-budget] missing budget file: ${budgetPath}`);
		return 2;
	}

	let graph;
	let budget;
	let routesByPath;
	try {
		graph = JSON.parse(readFileSync(graphPath, 'utf8'));
		budget = JSON.parse(readFileSync(budgetPath, 'utf8'));
		routesByPath = parseRouteTree(readFileSync(routeTreePath, 'utf8'));
	} catch (error) {
		console.error(`[bundle-budget] cannot parse input: ${error.message}`);
		return 2;
	}
	if (graph.schema_version !== 1 || typeof graph.chunks !== 'object') {
		console.error(`[bundle-budget] unsupported bundle graph schema: ${graph.schema_version}`);
		return 2;
	}

	const budgetErrors = validateBudget(budget, new Set(routesByPath.keys()));
	if (budgetErrors.length > 0) {
		console.error(`[bundle-budget] budget file ${relative(REPO_ROOT, budgetPath)} is invalid:`);
		for (const error of budgetErrors) console.error(`  - ${error}`);
		return 2;
	}

	const report = buildReport({
		graph,
		routesByPath,
		toolsDir,
		budget,
		sourceSha: currentSha(),
	});

	if (reportPath) {
		const target = resolve(reportPath);
		writeFileSync(target, `${JSON.stringify(report, null, '\t')}\n`);
		console.log(`[bundle-budget] report written to ${target}`);
	}

	if (asJson) {
		console.log(JSON.stringify(report, null, 2));
	} else {
		console.log(renderText(report));
	}

	for (const warning of report.warnings) {
		console.warn(`[bundle-budget] WARNING ${warning.message}`);
	}
	if (report.violations.length > 0) {
		console.error(`[bundle-budget] FAIL — ${report.violations.length} violation(s):`);
		for (const violation of report.violations) console.error(`  - ${violation.message}`);
		console.error(
			'[bundle-budget] reproduction conditions are printed above; rerun locally with `pnpm run build`.',
		);
		return 1;
	}
	for (const exception of report.exceptions) {
		console.warn(
			`[bundle-budget] ACKNOWLEDGED EXCEPTION ${exception.route} ${exception.metric}=${exception.measured} over ${exception.limit}: ${exception.reason}`,
		);
	}
	console.log('[bundle-budget] PASS — every measured route and Tool bundle is within budget.');
	return 0;
}

if (import.meta.url === `file://${process.argv[1]}`) {
	try {
		process.exit(main(process.argv.slice(2)));
	} catch (error) {
		console.error(`[bundle-budget] unexpected failure: ${error?.stack ?? error}`);
		process.exit(2);
	}
}
