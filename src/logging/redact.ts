/**
 * Log redaction contract (Issue #467).
 *
 * Why this module exists
 * ----------------------
 * The Worker, the browser bundle, and the Node scripts all emit
 * diagnostics through `console`. Every one of those streams is a
 * copy of runtime data that routinely carries an `Authorization`
 * header, a session cookie, an API key, an error message from an
 * upstream that echoed a request back, or an email address. Log
 * surfaces are read by people, shipped by `wrangler tail`, mirrored
 * by vendor dashboards, and pasted into Issues — so anything logged
 * must be treated as **public**.
 *
 * This module is the single redaction contract: every runtime log
 * call goes through `createAuditLogger` (`./logger.ts`), which
 * passes every argument through `redactLogValue` first. The gate
 * `scripts/check-log-redaction.mjs` fails the build if `src/**`
 * calls `console.*` directly outside `src/logging/`.
 *
 * Redaction is intentionally **lossy**: a value that cannot be
 * proven safe is replaced, not trusted. Over-redaction costs
 * debuggability; under-redaction costs a credential. When in doubt
 * this module masks, and the call site is expected to log a
 * narrower, purpose-built record instead of a raw payload (see
 * `describeAuthEmail` in `src/cloudflare/auth/better-auth.ts`).
 *
 * Contract summary:
 *   - Key-based: object properties whose NAME matches
 *     `isSensitiveKey` are replaced wholesale (`[redacted]`).
 *   - Value-based: string content is scanned for credential and
 *     personal-data shapes (Bearer tokens, JWTs, known key prefixes,
 *     query-string secrets, cookie pairs, email addresses, opaque
 *     blobs) regardless of where it came from.
 *   - Structural: depth, array length, object width, and string
 *     length are capped so a hostile payload cannot flood the log.
 *   - Errors collapse to `{ name, message }` with the message
 *     redacted; stacks and `cause` chains are dropped because both
 *     can carry request context from a framework. The NAME is
 *     attacker-controllable (`err.name = 'Bearer …'`), so it is
 *     allowlisted / redacted by `redactErrorName` instead of being
 *     written verbatim.
 */

/** Replacement for a value hidden by its KEY name. */
export const REDACTED = '[redacted]';
/** Replacement for an email address. */
export const REDACTED_EMAIL = '[redacted-email]';
/** Replacement for a credential-shaped value. */
export const REDACTED_TOKEN = '[redacted-token]';
/** Replacement for an opaque high-entropy run of token-ish characters. */
export const REDACTED_BLOB = '[redacted-blob]';
/** Replacement for a correlation token that is not provably safe. */
export const REDACTED_CORRELATION = '[redacted-correlation]';
/**
 * Replacement for an error name that is neither allowlisted nor
 * provably a plain identifier.
 */
export const REDACTED_ERROR_NAME = '[redacted-error-name]';

/**
 * Shape of a correlation token **this repository minted**: 128 bits of
 * lowercase hex, generated by `crypto.getRandomValues`. No client
 * input can produce one, and no secret is derived from it.
 *
 * Why the exception exists
 * -----------------------
 * The opaque-blob rule below is shaped to catch credentials: UUIDs,
 * session ids, opaque vendor tokens. A minted request id is the one
 * 24+ character value in the runtime that is deliberately published to
 * the client (response header + body, Issue #457) so an operator can
 * find the log line by grep. Masking it would make the published
 * correlation id useless while protecting nothing — it is fresh random
 * data, not anybody's secret.
 *
 * Why the exception is narrow
 * --------------------------
 * The value must match this exact shape. A client-supplied
 * `X-Request-Id` is accepted from a much wider alphabet
 * (`src/http/middleware/request-id.ts`), so a caller may only route a
 * token here after proving *it* minted it; anything else — including a
 * UUID-with-dashes, a `mk_…` API key, or an empty string — is
 * replaced. A caller that cannot prove minting passes `null`.
 */
const MINTED_CORRELATION_ID = /^[0-9a-f]{32}$/;

/**
 * Decide whether a correlation token may appear verbatim in a log
 * line. Fail-closed: only this repository's own mint format survives.
 */
export function redactCorrelationId(value: string | null | undefined): string {
	if (typeof value !== 'string') return REDACTED_CORRELATION;
	return MINTED_CORRELATION_ID.test(value) ? value : REDACTED_CORRELATION;
}

const MAX_DEPTH = 5;
const MAX_ARRAY_ITEMS = 25;
const MAX_OBJECT_KEYS = 40;
const MAX_STRING_LENGTH = 300;

/**
 * Property names whose VALUE is always replaced, regardless of
 * content. Matched case-insensitively against the whole key with
 * `_` / `-` treated as separators.
 *
 * `name` is deliberately absent: it is the most common key in the
 * codebase (`{ name: 'TypeError' }`, `r2_key`, bucket names) and
 * masking it would blind every error log while protecting nothing.
 */
const SENSITIVE_KEY_PATTERNS: readonly RegExp[] = [
	/^(?:authorization|proxy-authorization|www-authenticate)$/,
	/^(?:cookie|set-cookie)$/,
	/(?:^|[-_])(?:token|secret|password|passwd|credential)(?:$|[-_])/,
	/(?:^|[-_])api[-_]?key(?:$|[-_])/,
	/(?:^|[-_])(?:session|actor|visitor|user)[-_]?id(?:$|[-_])/,
	/^(?:email|email_address|phone|phone_number|address|ip|ip_address|user_agent)$/,
];

/** True when a property name means "never log this value verbatim". */
export function isSensitiveKey(key: string): boolean {
	// camelCase is normalized to snake_case first, so `refreshToken`
	// and `apiKey` are caught by the same separator-aware patterns as
	// their kebab/snake spellings.
	const normalized = key.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
	return SENSITIVE_KEY_PATTERNS.some((pattern) => pattern.test(normalized));
}

const EMAIL_PATTERN = /[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+/g;
/**
 * `Authorization: Bearer …` style headers. The credential run must be
 * at least 16 characters so ordinary prose (`token expired`) keeps
 * its wording.
 */
const AUTH_SCHEME_PATTERN =
	/(\b(?:bearer|basic|digest|token|apikey)\s+)([A-Za-z0-9._~+/=-]{16,})/gi;
const JWT_PATTERN = /\beyJ[A-Za-z0-9_-]{4,}\.[A-Za-z0-9_-]{4,}\.[A-Za-z0-9_-]{4,}/g;
/**
 * Vendor key shapes. `mk_` is this project's Better Auth API key
 * prefix (`src/cloudflare/auth/better-auth.ts`); the rest are
 * well-known prefixes whose *shape* alone identifies a credential.
 * Extend this list rather than adding ad-hoc call-site filters — a
 * call-site filter protects one caller, this pattern protects all.
 */
const KEY_PREFIX_PATTERN =
	/\b(?:mk_|sk-|sk_live_|rk_live_|pk_|ghp_|github_pat_|gho_|glpat-|xox[abprs]-|AKIA|ASIA|AIza)[A-Za-z0-9._-]{3,}/g;
/** `?token=…`, `&api_key=…`, `#access_token=…` in any URL-ish string. */
const QUERY_SECRET_PATTERN =
	/([?&#](?:token|access_token|refresh_token|id_token|api[-_]?key|apikey|key|secret|password|passwd|auth|authorization|code|session|session_id|sid)=)[^&#\s"'<>]+/gi;
/**
 * `Cookie: mw_actor_id=…`, `authorization=Bearer …`. The value runs
 * to the next `;` / `,` / newline so a multi-pair cookie header is
 * masked as a whole.
 */
const HEADER_VALUE_PATTERN =
	/\b((?:set-)?cookie|authorization|proxy-authorization)\s*[:=][^\n;,]*/gi;
/**
 * A run of token-ish characters long enough to be an opaque
 * credential (UUIDs included: they are frequently session or actor
 * identifiers, which are personal data under the audit contract).
 * Separator characters (`:`, `?`, spaces) are excluded, so ordinary
 * URLs and Japanese prose survive intact.
 */
const OPAQUE_BLOB_PATTERN = /(?<![A-Za-z0-9._~+/=-])[A-Za-z0-9._~+/=-]{24,}(?![A-Za-z0-9._~+/=-])/g;

/**
 * Redact credential and personal-data shapes inside one string.
 * Pure, total, and idempotent — running it twice yields the same
 * string, so it is safe to apply at more than one layer.
 */
export function redactLogText(text: string): string {
	return text
		.replace(EMAIL_PATTERN, REDACTED_EMAIL)
		.replace(JWT_PATTERN, REDACTED_TOKEN)
		.replace(AUTH_SCHEME_PATTERN, `$1${REDACTED_TOKEN}`)
		.replace(KEY_PREFIX_PATTERN, REDACTED_TOKEN)
		.replace(HEADER_VALUE_PATTERN, `$1: ${REDACTED}`)
		.replace(QUERY_SECRET_PATTERN, `$1${REDACTED}`)
		.replace(OPAQUE_BLOB_PATTERN, REDACTED_BLOB);
}

/** Redact a bare email address (used where only the address is known). */
export function redactEmailAddress(address: string): string {
	return address.length === 0 ? address : REDACTED_EMAIL;
}

/**
 * Error names that are known to carry no runtime data.
 *
 * Why an allowlist exists
 * -----------------------
 * `Error.prototype.name` is an ordinary writable string property.
 * Anyone who can reach the `catch` site can set it, and an upstream
 * that echoes a request back can put anything there
 * (`err.name = 'Bearer mk_…'`). The name used to be written to the
 * log verbatim, so a hostile or sloppy upstream could smuggle a
 * credential into an operator-visible record under a key that reads
 * like a type name.
 */
const ALLOWED_ERROR_NAMES: ReadonlySet<string> = new Set([
	'Error',
	'TypeError',
	'RangeError',
	'SyntaxError',
	'ReferenceError',
	'EvalError',
	'URIError',
	'AggregateError',
	'DOMException',
	'AbortError',
	'TimeoutError',
	'HttpError',
	'NonError',
]);

/**
 * A name that looks like a class / error identifier: a letter, then
 * letters, digits or underscores, at most 64 characters.
 *
 * This is the second gate for a name that is NOT on the allowlist.
 * It keeps this repository's own error classes (`BoundaryInputError`,
 * `KanataParseError`, …) readable without a coupling from this leaf
 * module to the modules that declare them, while refusing anything
 * that could be a smuggled value.
 */
const SAFE_ERROR_NAME_PATTERN = /^[A-Za-z][A-Za-z0-9_]{0,63}$/;

/**
 * Decide whether an error NAME may appear verbatim in a log record.
 *
 * Three steps, fail-closed:
 *   1. An allowlisted standard name is kept.
 *   2. Any other name is routed through the ordinary text redaction,
 *      so a credential shape (`Bearer …`, `sk_…`, a long opaque blob,
 *      an e-mail address) is masked.
 *   3. What survives must still look like a plain identifier. A
 *      masked or otherwise non-identifier result becomes
 *      `[redacted-error-name]` — the operator learns that the name was
 *      untrustworthy without learning what it said.
 */
export function redactErrorName(name: unknown): string {
	if (typeof name !== 'string' || name.length === 0) return REDACTED_ERROR_NAME;
	if (ALLOWED_ERROR_NAMES.has(name)) return name;
	const redacted = truncate(redactLogText(name));
	return SAFE_ERROR_NAME_PATTERN.test(redacted) ? redacted : REDACTED_ERROR_NAME;
}

function truncate(text: string): string {
	if (text.length <= MAX_STRING_LENGTH) return text;
	return `${text.slice(0, MAX_STRING_LENGTH)}…(+${text.length - MAX_STRING_LENGTH} chars)`;
}

function redactUnknown(value: unknown, depth: number, seen: Set<object>): unknown {
	if (value === null || value === undefined) return value;
	switch (typeof value) {
		case 'string':
			return truncate(redactLogText(value));
		case 'number':
		case 'boolean':
			return value;
		case 'bigint':
			return `${value.toString()}`;
		case 'symbol':
		case 'function':
			return `[${typeof value}]`;
		default:
			break;
	}

	const object = value as object;
	if (seen.has(object)) return '[circular]';
	if (depth >= MAX_DEPTH) return '[depth-limit]';

	if (value instanceof Error) {
		// Collapse to name + redacted message. The stack is dropped:
		// framework stacks can embed request URLs, and the message is
		// the only part an operator acts on.
		return redactLogError(value);
	}
	if (Array.isArray(value)) {
		seen.add(object);
		const items = value
			.slice(0, MAX_ARRAY_ITEMS)
			.map((item) => redactUnknown(item, depth + 1, seen));
		seen.delete(object);
		if (value.length > MAX_ARRAY_ITEMS) {
			items.push(`[+${value.length - MAX_ARRAY_ITEMS} more]`);
		}
		return items;
	}

	const prototype = Object.getPrototypeOf(value) as object | null;
	if (prototype !== null && prototype !== Object.prototype) {
		// Class instances (Headers, Request, Response, D1 rows, …) can
		// carry arbitrary state behind getters. Log the class name
		// instead of walking them.
		// The class name is attacker-reachable in the same way
		// `Error.name` is: an own `constructor` property can carry
		// any string, so it goes through the same name contract.
		const rawName = (value as { constructor?: { name?: unknown } }).constructor?.name;
		const name =
			typeof rawName === 'string' && rawName.length > 0 ? redactErrorName(rawName) : 'object';
		return `[${name}]`;
	}

	seen.add(object);
	const out: Record<string, unknown> = {};
	const keys = Object.keys(value as Record<string, unknown>);
	for (const key of keys.slice(0, MAX_OBJECT_KEYS)) {
		const raw = (value as Record<string, unknown>)[key];
		// `defineProperty`, not `out[key] = …`: an own `__proto__`
		// key (which `JSON.parse` produces from an untrusted body)
		// would otherwise mutate `out`'s PROTOTYPE instead of being
		// redacted as data, and the field would vanish from the
		// record the operator reads.
		Object.defineProperty(out, key, {
			value: isSensitiveKey(key) ? REDACTED : redactUnknown(raw, depth + 1, seen),
			enumerable: true,
			writable: true,
			configurable: true,
		});
	}
	seen.delete(object);
	if (keys.length > MAX_OBJECT_KEYS) {
		out['[truncated]'] = `${keys.length - MAX_OBJECT_KEYS} more keys`;
	}
	return out;
}

/**
 * Structured redaction for an arbitrary log argument. Primitives
 * survive (numbers and booleans stay typed); everything else is
 * rebuilt into a redacted, bounded shape.
 */
export function redactLogValue(value: unknown): unknown {
	return redactUnknown(value, 0, new Set());
}

export interface RedactedError {
	name: string;
	message: string;
}

/**
 * Collapse any thrown value into `{ name, message }` with the
 * message redacted. Non-`Error` throws (strings, objects) are
 * still redacted, so a `throw 'Bearer …'` cannot leak either.
 */
export function redactLogError(error: unknown): RedactedError {
	if (error instanceof Error) {
		const message = truncate(redactLogText(error.message));
		return { name: redactErrorName(error.name), message };
	}
	return { name: 'NonError', message: truncate(redactLogText(stringifyUnknown(error))) };
}

function stringifyUnknown(value: unknown): string {
	if (typeof value === 'string') return value;
	try {
		return JSON.stringify(redactLogValue(value)) ?? String(value);
	} catch {
		return String(value);
	}
}
