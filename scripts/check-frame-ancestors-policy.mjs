#!/usr/bin/env node

/**
 * Static embed-policy gate for Cloudflare Static Assets (Issue #448).
 *
 * Why this gate exists
 * --------------------
 * The embed policy has two enforcement points, and only one of them is
 * observable from the test pool:
 *
 *   | half                    | owner                            | observed by |
 *   | ----------------------- | -------------------------------- | ----------- |
 *   | Worker responses        | `src/server.ts`                 | `SELF.fetch` in `test/integration/frame-ancestors.test.ts` |
 *   | Static Assets responses | `public/_headers`               | nothing — the workerd pool declares no `assets` binding, so `_headers` is never applied there |
 *
 * Cloudflare documents that `_headers` "are not applied to responses
 * generated by your Worker code" (see the Scope limit note in that
 * file and in `src/server.ts`), so the reverse is equally true: a
 * rule in `_headers` that would break or widen framing is invisible to
 * every runtime test. That is exactly where the regression this gate
 * guards would land:
 *
 *   - a Tool artefact rule edited to `'none'` breaks every integrated
 *     Tool silently (the shell still renders; the iframe just never
 *     mounts), and
 *   - a rule edited to `*` silently re-opens third-party framing,
 *     undoing the Admin / Account denial this issue exists to add.
 *
 * What it asserts, narrowly
 * -------------------------
 *   1. Every `Content-Security-Policy` in `_headers` carries exactly
 *      one `frame-ancestors` directive (no silent second opinion).
 *   2. No `frame-ancestors` value is permissive. `'none'` and `'self'`
 *      are the only values this site ships; `*`, `https:` and absolute
 *      origins are rejected by name in the failure message so the fix
 *      is obvious.
 *   3. Every rule under the Tool artefact namespace carries
 *      `frame-ancestors 'self'` — the value that keeps the existing
 *      Tool iframes working, and the direction a careless edit breaks.
 *   4. No rule targets `/admin*` or `/api/v1/auth*`. Those responses
 *      are Worker-generated, so such a rule can never apply; it would
 *      be dead configuration that reads as if it protected something.
 *   5. Every committed public HTML document (any `.html` file under
 *      `public/`, e.g. `/share/procon2026/index.html`) is covered by at
 *      least one rule that carries `frame-ancestors`. A Static Assets
 *      response with no CSP has NO stated framing policy at all, and no
 *      Worker rule can reach it — Static Assets answer before the Worker
 *      runs — so a public namespace added under `public/` would
 *      otherwise ship framable by any third party, silently.
 *   6. Canary: `src/server.ts` still carries the Worker half. If that
 *      policy is moved or deleted, this gate fails with a message
 *      telling the reader to update it rather than silently guarding
 *      only one half.
 *
 * Scanner limits (documented, not hidden): the reader is
 * format-specific — Cloudflare/Netlify `_headers`, where a rule
 * pattern starts at column 0 and its `Name: Value` headers are
 * indented. It does not implement the full path-matching grammar; the
 * normalization below (strip `*`, strip `:param` segments) is enough to
 * classify a pattern as Tool / Admin / Account, and an unrecognized
 * pattern is left to rules 1-2 rather than guessed at. Rule 5 does match
 * patterns against concrete paths, but only with the subset the grammar
 * needs here: `:param` is one path segment and `*` is "anything to the
 * end". The document set is a filesystem scan of `public/`, which is
 * the directory Static Assets serves, so a generated Tool artefact
 * (built into `dist/client/tools/`, never `public/`) is out of scope by
 * construction.
 *
 * Exit codes: 0 = policy intact, 1 = at least one violation, 2 = bad
 * input (unreadable / unparseable file).
 *
 * Authority: Issue #448. Paired with `docs/security.md`.
 */

import { readFileSync, readdirSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Header that carries the inbound embed policy. */
const CSP_HEADER = 'content-security-policy';

/** The only directive this site's Static Assets half sets. */
const FRAME_ANCESTORS = 'frame-ancestors';

/** Values this site ships. Anything else is permissive or a typo. */
const ALLOWED_VALUES = new Set(["'none'", "'self'"]);

/** Prefixes whose responses are Worker-generated, never Static Assets. */
const WORKER_OWNED_PREFIXES = ['/admin', '/api/v1/auth'];

/** Prefix whose responses are Static Assets (Tool build artefacts). */
const TOOL_ARTEFACT_PREFIX = '/tools';

/**
 * Parse a `_headers` file into rules.
 *
 * A line whose first non-space character is not `#` and which starts
 * at column 0 opens a rule; the following indented non-comment lines
 * are its `Name: Value` headers. A malformed header line is collected
 * instead of thrown so the caller can report every problem at once.
 */
export function parseHeadersFile(text) {
	const rules = [];
	const problems = [];
	let current = null;

	for (const [index, rawLine] of text.split('\n').entries()) {
		const line = rawLine.replace(/\r$/, '');
		if (line.trim() === '') continue;
		const isComment = line.trimStart().startsWith('#');
		if (!isComment && !/^\s/.test(line)) {
			current = { pattern: line.trim(), line: index + 1, headers: [] };
			rules.push(current);
			continue;
		}
		if (isComment) continue;
		if (!current) {
			problems.push(`line ${index + 1}: header before any rule pattern: ${line.trim()}`);
			continue;
		}
		const header = /^([^:\s][^:]*):\s*(.*)$/.exec(line.trim());
		if (!header) {
			problems.push(`line ${index + 1}: not a "Name: Value" header: ${line.trim()}`);
			continue;
		}
		current.headers.push({ name: header[1].trim(), value: header[2].trim(), line: index + 1 });
	}

	return { rules, problems };
}

/**
 * Reduce a rule pattern to a comparable path prefix: wildcards and
 * `:param` placeholders are dropped, because the classification below
 * only asks "which namespace is this rule about".
 *
 * `/tools/:slug/app/*` -> `/tools/app`, `/admin*` -> `/admin`.
 */
export function normalizePattern(pattern) {
	return pattern
		.replace(/\*+$/, '')
		.replace(/\/\:[^/]*/g, '')
		.replace(/\/+$/, '');
}

/** True when `pattern` addresses `prefix` or something below it. */
export function isUnder(pattern, prefix) {
	const base = normalizePattern(pattern);
	return base === prefix || base.startsWith(`${prefix}/`);
}

/**
 * Compile a `_headers` pattern to a RegExp over a concrete request path.
 *
 * Only the two placeholders the shipped rules use are honoured: `:param`
 * is exactly one path segment and `*` runs to the end. Every other
 * character is matched literally (regex metacharacters escaped), so a
 * path cannot be talked into matching by its own punctuation.
 */
function patternToRegExp(pattern) {
	const METACHARACTERS = '.\\+?^$()[]{}|';
	let source = '^';
	for (let index = 0; index < pattern.length; index += 1) {
		const char = pattern[index];
		if (char === '*') {
			source += '.*';
		} else if (char === ':') {
			while (index < pattern.length && pattern[index] !== '/') index += 1;
			source += '[^/]+';
			index -= 1;
		} else {
			source += METACHARACTERS.includes(char) ? `\\${char}` : char;
		}
	}
	return new RegExp(`${source}$`);
}

/** True when a `_headers` rule pattern matches a concrete served path. */
export function patternMatchesPath(pattern, requestPath) {
	return patternToRegExp(pattern).test(requestPath);
}

/**
 * Every committed HTML document under `public/`, as the paths Static
 * Assets serves it under.
 *
 * An `index.html` is reported with both forms because Static Assets
 * answers `/share/<slug>/` (directory) and `/share/<slug>/index.html`
 * (explicit file); a rule that covers one but not the other would leave
 * a framable URL. Returns POSIX-style paths so the scan is comparable
 * across platforms.
 */
export function findStaticHtmlDocuments(publicDir) {
	const documents = [];
	const walk = (dir) => {
		for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
			a.name < b.name ? -1 : 1,
		)) {
			const absolute = join(dir, entry.name);
			if (entry.isDirectory()) {
				walk(absolute);
				continue;
			}
			if (!entry.isFile() || !entry.name.toLowerCase().endsWith('.html')) continue;
			const served = `/${relative(publicDir, absolute).split(sep).join('/')}`;
			documents.push({
				file: served,
				paths: served.endsWith('/index.html')
					? [served.slice(0, -'index.html'.length), served]
					: [served],
			});
		}
	};
	walk(resolve(publicDir));
	return documents;
}

/** Every `frame-ancestors` directive value carried by a header value. */
export function frameAncestorsValues(cspValue) {
	return String(cspValue)
		.split(';')
		.map((directive) => directive.trim())
		.filter(
			(directive) =>
				directive.toLowerCase().startsWith(`${FRAME_ANCESTORS} `) ||
				directive.toLowerCase() === FRAME_ANCESTORS,
		)
		.map((directive) => directive.slice(FRAME_ANCESTORS.length).trim());
}

/**
 * Every public HTML document the rules leave framable by any third
 * party. Returns the list of violations; empty means covered.
 *
 * A document counts as covered when at least one matching rule carries a
 * `Content-Security-Policy` with a `frame-ancestors` directive. The
 * VALUE is rule 2's business (`evaluateEmbedPolicy` rejects a permissive
 * one); this only asserts that the namespace states a policy at all,
 * because no Worker rule can reach a Static Assets response.
 */
export function evaluateStaticHtmlCoverage(rules, documents) {
	const errors = [];
	for (const document of documents) {
		const covered = rules.some((rule) => {
			const matched = document.paths.some((path) => patternMatchesPath(rule.pattern, path));
			if (!matched) return false;
			return rule.headers.some(
				(header) =>
					header.name.toLowerCase() === CSP_HEADER && frameAncestorsValues(header.value).length > 0,
			);
		});
		if (covered) continue;
		const patterns = rules.map((rule) => rule.pattern).join(', ') || '(none)';
		errors.push(
			`${document.file} (public HTML document): no _headers rule matches it with a ${FRAME_ANCESTORS} directive. Static Assets answer before the Worker runs, so src/server.ts cannot cover this document and it currently carries no framing policy — any third-party site may iframe it. Add a rule (e.g. \`/share/*\` with \`${CSP_HEADER}: ${FRAME_ANCESTORS} 'self'\`); matching rules today: ${patterns}.`,
		);
	}
	return errors;
}

/**
 * Evaluate one parsed `_headers` document against the embed policy.
 * Returns the list of violations; empty means intact.
 *
 * `staticHtml` is the output of {@link findStaticHtmlDocuments}. It is
 * optional so a fixture-only caller can evaluate the header rules alone;
 * the CLI always passes the real document set.
 */
export function evaluateEmbedPolicy(rules, staticHtml = []) {
	const errors = [];

	for (const rule of rules) {
		const cspHeaders = rule.headers.filter((h) => h.name.toLowerCase() === CSP_HEADER);
		const isToolArtefact = isUnder(rule.pattern, TOOL_ARTEFACT_PREFIX);
		const isWorkerOwned = WORKER_OWNED_PREFIXES.some((prefix) => isUnder(rule.pattern, prefix));

		if (isWorkerOwned) {
			errors.push(
				`${rule.pattern} (line ${rule.line}): rule targets a Worker-generated response. Cloudflare does not apply \`_headers\` to responses generated by Worker code, so this rule can never take effect. The embed policy for ${rule.pattern} lives in src/server.ts.`,
			);
		}

		if (cspHeaders.length === 0) {
			if (isToolArtefact) {
				errors.push(
					`${rule.pattern} (line ${rule.line}): Tool artefact rule sets no ${CSP_HEADER}. Without it a Tool document carries no frame-ancestors at all, which leaves third-party framing unstated — add \`${CSP_HEADER}: ${FRAME_ANCESTORS} 'self'\`.`,
				);
			}
			continue;
		}

		for (const header of cspHeaders) {
			const values = frameAncestorsValues(header.value);
			if (values.length === 0) {
				errors.push(
					`${rule.pattern} (line ${header.line}): ${CSP_HEADER} carries no ${FRAME_ANCESTORS} directive.`,
				);
				continue;
			}
			if (values.length > 1) {
				errors.push(
					`${rule.pattern} (line ${header.line}): ${FRAME_ANCESTORS} is declared ${values.length} times (${values.join(' | ')}). Browsers ignore every duplicate but the first, so the rest is misleading dead configuration.`,
				);
			}
			for (const value of values) {
				if (!ALLOWED_VALUES.has(value)) {
					errors.push(
						`${rule.pattern} (line ${header.line}): ${FRAME_ANCESTORS} ${value} is not a value this site ships. Use 'self' (same-origin ancestors only) or 'none' (no ancestor at all); \`*\`, \`https:\` and absolute origins all re-open third-party framing.`,
					);
					// Reported once. The Tool-specific message below would
					// restate the same edit as "breaks every Tool" and bury
					// the value that actually has to change.
					continue;
				}
				if (isToolArtefact && value !== "'self'") {
					errors.push(
						`${rule.pattern} (line ${header.line}): Tool artefacts are framed BY the host shell at /tools/<slug> (same origin), so their ${FRAME_ANCESTORS} must be 'self'. \`${value}\` breaks every integrated Tool: the shell renders, the iframe never mounts.`,
					);
				}
			}
		}
	}

	return [...errors, ...evaluateStaticHtmlCoverage(rules, staticHtml)];
}

/**
 * Canary for the Worker half. Textual by design: it is here to notice
 * that `src/server.ts` stopped carrying the policy at all, so the gate
 * cannot quietly end up guarding one half of a two-half contract.
 */
export function evaluateWorkerCanary(serverSource) {
	const errors = [];
	if (!/content-security-policy/i.test(serverSource)) {
		errors.push(
			'src/server.ts no longer mentions content-security-policy. The Worker half of the embed policy (`frame-ancestors` on Admin / Account and on public documents) lives there; update this canary if the policy moved to another module.',
		);
	}
	if (!/frame-ancestors/i.test(serverSource)) {
		errors.push('src/server.ts no longer mentions the frame-ancestors directive.');
	}
	for (const value of ALLOWED_VALUES) {
		if (!serverSource.includes(value)) {
			errors.push(
				`src/server.ts no longer contains the ${FRAME_ANCESTORS} ${value} literal; the deny list and the public default are expected to name both values.`,
			);
		}
	}
	return errors;
}

function main(argv) {
	const headersPath = argv.headers
		? resolve(REPO_ROOT, argv.headers)
		: join(REPO_ROOT, 'public/_headers');
	const publicDir = argv.public ? resolve(REPO_ROOT, argv.public) : join(REPO_ROOT, 'public');
	const serverPath = join(REPO_ROOT, 'src/server.ts');

	let headersText;
	let serverSource;
	let staticHtml;
	try {
		headersText = readFileSync(headersPath, 'utf8');
		serverSource = readFileSync(serverPath, 'utf8');
		staticHtml = findStaticHtmlDocuments(publicDir);
	} catch (error) {
		process.stderr.write(`cannot read ${error.path ?? 'input'}: ${error.message}\n`);
		return 2;
	}

	const { rules, problems } = parseHeadersFile(headersText);
	const errors = [
		...problems,
		...evaluateEmbedPolicy(rules, staticHtml),
		...evaluateWorkerCanary(serverSource),
	];

	if (errors.length === 0) {
		process.stdout.write(
			`embed policy OK: ${rules.length} _headers rule(s), ${staticHtml.length} public HTML document(s) covered, Tool artefacts framed by 'self' only, no rule targets a Worker-owned path\n`,
		);
		return 0;
	}

	process.stderr.write(`${errors.length} embed-policy violation(s):\n`);
	for (const error of errors) process.stderr.write(`  - ${error}\n`);
	process.stderr.write(
		'\nSee docs/security.md#csp-frame-ancestors (Issue #448) for the policy table and the\n' +
			'reasoning behind the two halves (Worker responses vs Static Assets).\n',
	);
	return 1;
}

/** Minimal `--headers=<path>` / `--public=<dir>` parsing so the gate can run on a fixture. */
function parseArgs(argv) {
	const args = { headers: null, public: null };
	for (const entry of argv) {
		if (entry.startsWith('--headers=')) args.headers = entry.slice('--headers='.length);
		if (entry.startsWith('--public=')) args.public = entry.slice('--public='.length);
	}
	return args;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	process.exit(main(parseArgs(process.argv.slice(2))));
}

export { main };
