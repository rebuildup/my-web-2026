describe('provenance — .gitmodules parsing', () => {
	it('reads path, url and unknown keys, and ignores comments', () => {
		const sections = parseGitmodules(`
# a comment
[submodule "external/example-widget"]
	path = external/example-widget
	url = ${CANONICAL}
	branch = main
[submodule "external/other"]
	path = external/other
	url = git@github.com:example-org/other.git
`);
		assert.equal(sections.length, 2);
		assert.equal(sections[0].name, 'external/example-widget');
		assert.equal(sections[0].path, 'external/example-widget');
		assert.equal(sections[0].url, CANONICAL);
		assert.equal(sections[0].keys.branch, 'main');
		assert.equal(sections[1].url, 'git@github.com:example-org/other.git');
	});

	it('returns no sections for a missing file body', () => {
		assert.deepEqual(parseGitmodules(''), []);
		assert.deepEqual(parseGitmodules(undefined), []);
	});
});

describe('provenance — git plumbing parsing', () => {
	it('keeps only gitlink (mode 160000) entries', () => {
		const links = parseGitlinkStdout(
			[
				'100644 blob 1111111111111111111111111111111111111111\tREADME.md',
				'160000 commit aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\texternal/example-widget',
			].join('\n'),
		);
		assert.deepEqual(links, { 'external/example-widget': PIN_A });
	});

	it('splits submodule config keys from the right', () => {
		assert.deepEqual(splitSubmoduleConfigKey('submodule.external/example-widget.branch'), {
			name: 'external/example-widget',
			configKey: 'branch',
		});
		assert.deepEqual(splitSubmoduleConfigKey('submodule.external/readmark.update'), {
			name: 'external/readmark',
			configKey: 'update',
		});
		assert.equal(splitSubmoduleConfigKey('url.https://github.com/.insteadof'), null);
	});
});

describe('provenance — fetch-source URL policy', () => {
	it('normalises equivalent https URLs', () => {
		assert.equal(normalizeRepoUrl(CANONICAL), 'github.com/example-org/example-widget');
		assert.equal(
			normalizeRepoUrl('https://GitHub.com/example-org/example-widget.git/'),
			'github.com/example-org/example-widget',
		);
		assert.equal(normalizeRepoUrl('git@github.com:example-org/example-widget.git'), null);
		assert.equal(normalizeRepoUrl('https://github.com/example-org/a b.git'), null);
	});

	it('accepts a credential-free github https repository URL', () => {
		const verdict = classifyRepoUrl(CANONICAL);
		assert.equal(verdict.ok, true);
		assert.equal(verdict.code, 'URL_OK');
	});

	for (const bad of [
		'http://github.com/example-org/example-widget.git',
		'git@github.com:example-org/example-widget.git',
		'https://x-access-token:ghp_EXAMPLE@github.com/example-org/example-widget.git',
		'https://github.com/example-org/example-widget.git#main',
		'https://github.com/example-org/example-widget.git?ref=main',
		'https://gitlab.com/example-org/example-widget.git',
		'https://github.com/example-org/example-widget/tree/main',
		'/local/path/to/example-widget',
	]) {
		it(`rejects ${bad}`, () => {
			const verdict = classifyRepoUrl(bad);
			assert.equal(verdict.ok, false);
			assert.equal(verdict.code, 'URL_UNSAFE');
		});
	}
});

