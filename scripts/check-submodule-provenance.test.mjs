function widgetTool(overrides = {}) {
	return {
		slug: 'example-widget',
		display_name: 'Example Widget',
		source: {
			canonical_repo: CANONICAL,
			submodule_path: 'external/example-widget',
			pinned_sha: PIN_A,
			branch: 'main',
		},
		build: { command: 'true', output_dir: 'dist', package_manager: 'pnpm' },
		delivery: { kind: 'same_origin_static', artifact_path: '/tools/example-widget/app' },
		classification: 'same_origin_static',
		license: 'MIT',
		...overrides,
	};
}

const GITMODULES = parseGitmodules(`
# generated by hand for the fixture
[submodule "external/example-widget"]
	path = external/example-widget
	url = ${CANONICAL}
`);

function healthyFacts(overrides = {}) {
	return {
		gitAvailable: true,
		head: PIN_A,
		gitlinks: { 'external/example-widget': PIN_A },
		localSubmoduleConfig: {
			'external/example-widget': { url: CANONICAL, active: 'true' },
		},
		urlRewrites: [],
		checkouts: {
			'external/example-widget': {
				initialised: true,
				head: PIN_A,
				origin: CANONICAL,
				dirty: false,
				toplevelMatches: true,
			},
		},
		artifacts: {
			'example-widget': {
				schema: 1,
				slug: 'example-widget',
				canonical_repo: CANONICAL,
				pinned_sha: PIN_A,
				checkout_sha: PIN_A,
			},
		},
		...overrides,
	};
}

function run(tools, gitmodules, facts, options) {
	return verifySubmoduleProvenance({
		manifest: { version: 1, tools },
		gitmodules,
		facts,
		options,
	});
}

function codes(result) {
	return result.findings.map((item) => item.code);
}

