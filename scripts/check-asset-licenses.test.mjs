import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { after, describe, it } from 'node:test';
import { fileURLToPath } from 'node:url';

import {
	collectAuditedFiles,
	main,
	renderConsoleReport,
	renderHtmlReport,
	renderMarkdownReport,
	sha256OfFile,
} from './check-asset-licenses.mjs';

/**
 * Tests for the asset rights gate (Issue #497).
 *
 * Two layers, following `check-tool-artifact-inventory.test.mjs`:
 *
 *   1. Pure helpers: what counts as an audited file, and what the
 *      report is allowed to print.
 *   2. The gate itself, driven over a synthetic repository. Re-writing
 *      the refusals in the test would only prove the test's copy behaves.
 *
 * The two properties worth protecting: a contradiction is a non-zero
 * exit, and the output stays STATUS-ONLY. The fixture writes a
 * credential-SHAPED provider reference into the record precisely so a
 * regression that echoes a raw URL fails this suite instead of putting
 * someone else's credentials in a CI log.
 */

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const temporaryDirs = [];

function makeFixture(files) {
	const root = mkdtempSync(join(tmpdir(), 'asset-license-'));
	temporaryDirs.push(root);
	for (const [path, content] of Object.entries(files)) {
		const full = join(root, path);
		mkdirSync(dirname(full), { recursive: true });
		writeFileSync(full, content);
	}
	return root;
}

function recordFor(overrides = {}) {
	return {
		schema: 'asset-license-inventory.v1',
		issue: '#497',
		reviewedAt: '2026-10-19',
		scope: 'fixture',
		assets: [
			{
				id: 'fixture-icons',
				kind: 'image',
				title: 'fixture icons',
				summary: 'generated by the fixture',
				covers: ['public/icons/**'],
				publicPaths: ['/icons/one.png'],
				origin: 'repository-generated',
				rightsHolder: 'rebuildup',
				license: {
					spdx: 'MIT',
					redistribution: 'bundled',
					attributionRequired: false,
					attributionText: null,
					attributionDeliveredAt: null,
					conditions: ['MIT'],
				},
				verification: {
					method: 'repository-evidence',
					checkedOn: '2026-10-19',
					note: 'reviewed against the fixture bytes',
				},
				evidence: [
					{
						kind: 'repository-file',
						path: 'LICENSE',
						sha256: createHash('sha256').update('MIT fixture\n').digest('hex'),
					},
				],
				publication: 'published',
				externalHosts: [],
				...overrides,
			},
		],
	};
}

function runGate(argv = []) {
	return main(argv);
}

after(() => {
	for (const dir of temporaryDirs) rmSync(dir, { recursive: true, force: true });
});

describe('collectAuditedFiles', () => {
	it('collects every file under the audited roots, repository-relative and sorted', () => {
		const root = makeFixture({
			'public/icons/one.png': 'a',
			'public/og/two.png': 'b',
			'public/index.html': 'c',
			'docs/ignored.md': 'd',
			'src/not-audited.ts': 'e',
		});
		assert.deepEqual(collectAuditedFiles(root), [
			'public/icons/one.png',
			'public/index.html',
			'public/og/two.png',
		]);
	});
});

describe('sha256OfFile', () => {
	it('hashes the bytes and returns null for a path that does not exist', () => {
		const root = makeFixture({ 'public/icons/one.png': 'bytes' });
		assert.equal(
			sha256OfFile(root, 'public/icons/one.png'),
			createHash('sha256').update('bytes').digest('hex'),
		);
		assert.equal(sha256OfFile(root, 'public/icons/missing.png'), null);
	});
});

describe('the gate', () => {
	it('passes a repository whose audited files are all claimed', () => {
		const root = makeFixture({
			'public/icons/one.png': 'bytes',
			LICENSE: 'MIT fixture\n',
			'quality/asset-license-inventory.json': JSON.stringify(recordFor()),
		});
		const run = spawnSync(
			process.execPath,
			[join(repoRoot, 'scripts/check-asset-licenses.mjs'), `--root=${root}`],
			{ encoding: 'utf8' },
		);
		assert.equal(run.status, 0, run.stdout + run.stderr);
		assert.match(run.stdout, /asset license review — PASS/);
	});

	it('fails when an audited file is claimed by no record', () => {
		const root = makeFixture({
			'public/icons/one.png': 'bytes',
			'public/other/unreviewed.png': 'bytes',
			LICENSE: 'MIT fixture\n',
			'quality/asset-license-inventory.json': JSON.stringify(recordFor()),
		});
		const run = spawnSync(
			process.execPath,
			[join(repoRoot, 'scripts/check-asset-licenses.mjs'), `--root=${root}`],
			{ encoding: 'utf8' },
		);
		assert.equal(run.status, 1);
		assert.match(run.stdout + run.stderr, /L001 public\/other\/unreviewed\.png/);
	});

	it('fails when a pinned licence digest no longer matches', () => {
		const root = makeFixture({
			'public/icons/one.png': 'bytes',
			LICENSE: 'MIT fixture, edited after the review\n',
			'quality/asset-license-inventory.json': JSON.stringify(recordFor()),
		});
		const run = spawnSync(
			process.execPath,
			[join(repoRoot, 'scripts/check-asset-licenses.mjs'), `--root=${root}`],
			{ encoding: 'utf8' },
		);
		assert.equal(run.status, 1);
		assert.match(run.stdout + run.stderr, /L005 fixture-icons/);
	});

	it('fails when the record cannot be read at all', () => {
		const root = makeFixture({ 'public/icons/one.png': 'bytes' });
		const run = spawnSync(
			process.execPath,
			[join(repoRoot, 'scripts/check-asset-licenses.mjs'), `--root=${root}`],
			{ encoding: 'utf8' },
		);
		assert.equal(run.status, 2);
		assert.match(run.stderr, /unreadable record/);
	});

	it('fails closed on a record whose shape drifted', () => {
		const root = makeFixture({
			'public/icons/one.png': 'bytes',
			LICENSE: 'MIT fixture\n',
			'quality/asset-license-inventory.json': JSON.stringify(
				recordFor({ attributionDeliverdAt: '/licenses' }),
			),
		});
		const run = spawnSync(
			process.execPath,
			[join(repoRoot, 'scripts/check-asset-licenses.mjs'), `--root=${root}`],
			{ encoding: 'utf8' },
		);
		assert.equal(run.status, 1);
		assert.match(run.stdout + run.stderr, /J004/);
	});

	it('keeps a provider reference out of the report it prints', () => {
		// A credential-shaped reference: the record is INVALID (L016), and
		// the point of the test is that the report names the problem
		// without reproducing the URL.
		const root = makeFixture({
			'public/icons/one.png': 'bytes',
			LICENSE: 'MIT fixture\n',
			'quality/asset-license-inventory.json': JSON.stringify(
				recordFor({
					origin: 'third-party-referenced',
					covers: [],
					publicPaths: [],
					externalHosts: ['fonts.example'],
					evidence: [{ kind: 'external-reference', url: 'https://user:secret@fonts.example/' }],
				}),
			),
		});
		const run = spawnSync(
			process.execPath,
			[join(repoRoot, 'scripts/check-asset-licenses.mjs'), `--root=${root}`],
			{ encoding: 'utf8' },
		);
		assert.equal(run.status, 1);
		const output = `${run.stdout}${run.stderr}`;
		assert.match(output, /L016/);
		assert.doesNotMatch(output, /secret/);
		assert.doesNotMatch(output, /user:/);
	});

	it('never fails the committed repository, whatever the owner decides about the held assets', () => {
		const run = spawnSync(process.execPath, [join(repoRoot, 'scripts/check-asset-licenses.mjs')], {
			encoding: 'utf8',
		});
		// The verdict word itself is an owner decision (an asset may be
		// held or cleared), so this asserts the SHAPE instead: no
		// contradiction, every audited file claimed exactly once, and
		// every record decided from its evidence.
		assert.equal(run.status, 0, run.stdout + run.stderr);
		assert.doesNotMatch(run.stdout, /L001/);
		assert.doesNotMatch(run.stdout, /L002/);
		const audited = Number(/audited files: (\d+)/.exec(run.stdout)?.[1]);
		const claimed = [...run.stdout.matchAll(/(\d+) files/g)].reduce(
			(total, match) => total + Number(match[1]),
			0,
		);
		assert.equal(claimed, audited);
		// The fonts ship their licence text with the page, so they are
		// cleared from the embedded declaration; the assets whose rights
		// this repository cannot account for stay held.
		assert.match(
			run.stdout,
			/publishable\s+share-procon2026-fonts-noto-sans-jp\s+font\s+49 files\s+OFL-1\.1/,
		);
		assert.match(
			run.stdout,
			/publishable\s+share-procon2026-fonts-material-symbols\s+font\s+1 files\s+Apache-2\.0/,
		);
		assert.match(run.stdout, /hold\s+share-procon2026-pdfs/);
		assert.match(run.stdout, /hold\s+share-procon2026-images/);
	});

	it('lets one record hand a file to another without a double claim', () => {
		const base = recordFor().assets[0];
		const root = makeFixture({
			'public/fonts/a.woff2': 'bytes',
			'public/fonts/b.woff2': 'bytes',
			LICENSE: 'MIT fixture\n',
			'quality/asset-license-inventory.json': JSON.stringify({
				...recordFor(),
				assets: [
					{
						...base,
						id: 'fixture-fonts',
						covers: ['public/fonts/**'],
						excludes: ['public/fonts/b.woff2'],
					},
					{ ...base, id: 'fixture-one-font', covers: ['public/fonts/b.woff2'] },
				],
			}),
		});
		const run = spawnSync(
			process.execPath,
			[join(repoRoot, 'scripts/check-asset-licenses.mjs'), `--root=${root}`],
			{ encoding: 'utf8' },
		);
		assert.equal(run.status, 0, run.stdout + run.stderr);
		assert.doesNotMatch(run.stdout, /L001/);
		assert.doesNotMatch(run.stdout, /L002/);
	});

	it('writes a Markdown report when asked, into the given path', () => {
		const root = makeFixture({
			'public/icons/one.png': 'bytes',
			LICENSE: 'MIT fixture\n',
			'quality/asset-license-inventory.json': JSON.stringify(recordFor()),
		});
		const out = join(root, 'report.md');
		const run = spawnSync(
			process.execPath,
			[
				join(repoRoot, 'scripts/check-asset-licenses.mjs'),
				`--root=${root}`,
				'--report=markdown',
				`--report-out=${out}`,
			],
			{ encoding: 'utf8' },
		);
		assert.equal(run.status, 0, run.stdout + run.stderr);
		assert.match(readFileSync(out, 'utf8'), /資産の権利 \/ 出典 \/ ライセンス検証/);
	});

	it('refuses an unknown report format', () => {
		const root = makeFixture({
			'public/icons/one.png': 'bytes',
			LICENSE: 'MIT fixture\n',
			'quality/asset-license-inventory.json': JSON.stringify(recordFor()),
		});
		const exitCode = main([`--root=${root}`, '--report=pdf']);
		assert.equal(exitCode, 2);
	});

	it('refuses an unknown option', () => {
		assert.equal(main(['--nope']), 2);
	});
});

describe('report rendering', () => {
	const review = {
		id: 'fixture-icons',
		kind: 'image',
		origin: 'repository-generated',
		spdx: 'MIT',
		publication: 'published',
		decision: 'publishable',
		files: ['public/icons/one.png'],
		findings: [],
	};
	const finding = {
		code: 'L010',
		severity: 'warn',
		subject: 'held-asset',
		message: 'message with <markup> & an ampersand',
		remedy: 'remedy text',
	};
	const payload = {
		verdict: 'WARN',
		reviews: [review],
		findings: [finding],
		summary: {
			verdict: 'WARN',
			records: 1,
			auditedFileCount: 1,
			claimedFiles: 1,
			uncoveredFiles: 0,
			publishable: 1,
			hold: 0,
			providerTerms: 0,
			findings: 1,
			errors: 0,
			warnings: 1,
			infos: 0,
		},
		recordPath: 'quality/asset-license-inventory.json',
		auditedFileCount: 1,
	};

	it('prints one status line per record and per finding', () => {
		const text = renderConsoleReport(payload);
		assert.match(text, /asset license review — WARN/);
		assert.match(text, /publishable\s+fixture-icons/);
		assert.match(text, /WARN {2}L010 held-asset/);
		assert.match(text, /remedy: remedy text/);
	});

	it('renders a Markdown record with the counts', () => {
		const text = renderMarkdownReport(payload);
		assert.match(text, /判定: \*\*WARN\*\*/);
		assert.match(text, /`fixture-icons`/);
		assert.match(text, /## findings/);
	});

	it('escapes finding text in the HTML report', () => {
		const html = renderHtmlReport(payload);
		assert.match(html, /&lt;markup&gt; &amp; an ampersand/);
		assert.doesNotMatch(html, /<markup>/);
	});

	it('says "no findings" instead of rendering an empty list', () => {
		const html = renderHtmlReport({ ...payload, findings: [] });
		assert.match(html, /findings なし/);
	});
});
