export interface HomePageData {
	capabilities: readonly Capability[];
	services: readonly SystemService[];
	statuses: readonly SystemServiceStatus[];
	observedAt: string;
	/**
	 * The known-incident records the status section publishes
	 * (Issue #502). Optional because the safe default is the empty
	 * list: a surface that forgets the records publishes "no
	 * incidents recorded" rather than a stale one.
	 */
	incidents?: readonly KnownIncident[];
	reactions: HomeReactionsData;
	counter: HomeCounterData;
	/**
	 * The current-project records (Issue #316). Optional, and the
	 * default is the EMPTY list: a route that forgets them publishes
	 * the "nothing is published" sentence rather than a stale one.
	 * Every record is composed from committed artefacts (the owner's
	 * roster and the generated git snapshot) — there is no runtime
	 * fetch for this section.
	 */
	projects?: readonly CurrentProjectRecord[];
	/**
	 * Issue #377 — which data source the runtime is reading. The
	 * indicator renders only outside the deployed production Worker,
	 * so the shipped page carries no development text.
	 */
	dataSource?: DataSourceDescriptor;
	/**
	 * Issue #925 — portfolio projects promoted by the ad surface,
	 * mapped by the route from the public `listPortfolioProjects`
	 * read. Optional: the ad roster degrades to its Tool-only set
	 * when the portfolio read is unavailable or yields no covers.
	 */
	adProjects?: readonly HomeAdProject[];
	/**
	 * Issue #320 — the owner's Discord presence/activities/Rich Presence/
	 * custom status card. Optional: the section degrades to "unavailable"
	 * when the committed snapshot is missing, stale, or fails validation.
	 * The snapshot is generated by an operator-run script (committed JSON);
	 * the Worker never calls Discord at runtime.
	 */
	discordPresence?: DiscordPresenceCard;
}

export interface HomePageProps {
	data: HomePageData;
	/**
	 * Opt-in locale for the format adapter (Issue #430). The route
	 * passes nothing today, so the shipped page keeps the `'en'`
	 * default; picking the locale source (URL, cookie,
	 * `Accept-Language`) is a product decision this ticket does not
	 * make.
	 */
	locale?: HomeLocale;
	/**
	 * IANA time zone the observed-at snapshot is read in. Defaults to
	 * `'UTC'` — see `StatusTilesProps#timeZone`.
	 */
	timeZone?: string;
}

