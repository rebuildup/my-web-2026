describe('provenance — pinned SHA vs actual source SHA (Issue #473 headline)', () => {
	it('fails when the checked-out commit is not the pinned commit', () => {
		const facts = healthyFacts({
			checkouts: {
				'external/example-widget': {
					initialised: true,
					head: PIN_B,
					origin: CANONICAL,
					dirty: false,
					toplevelMatches: true,
				},
			},
		});
		const result = run([widgetTool()], GITMODULES, facts);
		assert.equal(result.ok, false);
		assert.ok(codes(result).includes('CHECKOUT_SHA_MISMATCH'));
		assert.equal(result.rows[0].verdict, 'FAIL');
		const finding = result.findings.find((item) => item.code === 'CHECKOUT_SHA_MISMATCH');
		assert.match(finding.message, new RegExp(PIN_B));
		assert.match(finding.message, new RegExp(PIN_A));
		assert.match(finding.remedy, /git -C external\/example-widget checkout/);
	});

	it('fails when the gitlink is not the pinned commit', () => {
		const facts = healthyFacts({ gitlinks: { 'external/example-widget': PIN_B } });
		const result = run([widgetTool()], GITMODULES, facts);
		assert.equal(result.ok, false);
		assert.ok(codes(result).includes('GITLINK_SHA_MISMATCH'));
	});

	it('fails when the pin is not a 40-char commit SHA', () => {
		const tool = widgetTool();
		tool.source.pinned_sha = 'main';
		const result = run([tool], GITMODULES, healthyFacts());
		assert.equal(result.ok, false);
		assert.ok(codes(result).includes('PINNED_SHA_INVALID'));
	});
});

