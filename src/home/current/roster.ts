/**
 * The current-projects roster — the file the OWNER edits (Issue #316).
 *
 * What lives here
 * ---------------
 * Which projects the "現在地 / Where I am now" section publishes, and every
 * word about them: `name`, the one-line `statusJa`, and — once the owner
 * writes them — the weight level and, for a project whose history is not
 * in this repository, its dates.
 *
 * What does NOT live here
 * -----------------------
 * Facts that a machine can produce. `my-web-2026` is this repository, so its
 * start date, last commit and commit counts come from git
 * (`src/home/current/git-facts.json`, regenerated by
 * `pnpm run current:facts:sync`). Writing those by hand would make a
 * reproducible value look like a memory.
 *
 * How to add or change a project
 * ------------------------------
 *   - To publish a project, add an entry with `id`, `name` and `statusJa`.
 *     An entry with nothing measured is still a valid entry: the section
 *     shows the name and the one-liner, and omits the facts it does not
 *     have. It never renders "未記入".
 *   - To publish dates for a project whose history is NOT in this
 *     repository, add a `handwritten` block. `recordedOn` is the day you
 *     wrote the values (it is the only evidence a hand-written value can
 *     carry); `startedOn` and `updatedOn` are written as a PAIR — one date
 *     without the other is not published, because a duration needs both.
 *   - To publish a weight, add `weightLevel` to that block:
 *     `主軸` = primary / `並行` = active / `副次` = side / `休止` = paused.
 *     Levels are shown per row when only some projects have one, and become
 *     group headings when every published project has one.
 *   - To publish a link, add `link: { label, href }`. Only an internal path
 *     or an `https://` URL is published; an unusable link disappears and
 *     the project stays.
 *
 * The structure gate (`./source.ts`) refuses an entry whose dates are not a
 * real `YYYY-MM-DD`, whose start follows its last update, or whose dates
 * are in the future. It checks STRUCTURE, not truth: it cannot know whether
 * the dates are the ones you actually worked on.
 *
 * Owner confirmation: PENDING. The four ids below are the projects the
 * `/about` "current" narrative already publishes (`src/about/data.ts`), and
 * `test/integration/home-about-current-consistency.test.ts` pins the two
 * pages together. No dates, levels or links are written yet — this file has
 * no invented values in it, and the section is designed to render correctly
 * while that stays true.
 */

